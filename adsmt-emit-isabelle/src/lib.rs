/// A lemma discharged by the registered `adsmt` oracle.
///
/// `axiomatization` would also make the statement available, but it does
/// not register a trust source: `Thm_Deps.all_oracles` reports nothing for
/// it. Going through the oracle makes the trust both named and countable,
/// which is what the acceptance criterion checks.
fn isa_oracle_lemma(name: &str, prop: &str) -> String {
    isa_oracle_lemma_via("adsmt", name, prop)
}

/// Same, through a NAMED oracle — so a user assumption and a theory
/// decision are two distinct entries in `Thm_Deps.all_oracles` rather
/// than one indistinguishable count.
fn isa_oracle_lemma_via(oracle: &str, name: &str, prop: &str) -> String {
    // `\<^cprop>`, not `\<^cterm>`: an oracle's result must have type
    // `prop`. A statement like `q \<Longrightarrow> False` is already a
    // `prop` and passes either way, but a bare `bool` proposition — the
    // shape a user assumption takes — is rejected with "Oracle's result
    // must have type prop" unless it goes through `Trueprop`, which is
    // exactly what `\<^cprop>` inserts.
    format!(
        "lemma {name}: \"{prop}\"\n  \
         by (tactic \\<open>resolve_tac \\<^context> \
         [{oracle} \\<^cprop>\\<open>{prop}\\<close>] 1\\<close>)"
    )
}

/// The Isabelle **session** for the emitted theory.
///
/// The emitted `.thy` is Isabelle/HOL-specific — `Main`, `bool`, the
/// `\<Longrightarrow>` / `Trueprop` boundary, HOL tactics. Shipping the ROOT
/// alongside it pins that dependency in a file rather than leaving it
/// implicit, and it is what makes `isabelle build` runnable at all: the
/// acceptance criterion is stated in terms of that command.
pub fn emit_isabelle_root() -> String {
    "chapter AdsmtCert\n\n\
     session AdsmtCert = HOL +\n  \
     description \"adsmt certificate, emitted\"\n  \
     options [timeout = 300]\n  \
     theories\n    AdsmtCert\n"
        .to_owned()
}

/// Constants the emitter knows how to render. Anything else is an
/// UNMAPPED symbol: adsmt's name is passed through verbatim, which is
/// how `> x 5` once reached Isabelle as prefix application and failed to
/// parse. Callers can ask for the list to surface the gap instead of
/// discovering it downstream.
pub fn unmapped_constants(cert: &Certificate) -> Vec<String> {
    const KNOWN: &[&str] = &[
        "true", "false", "not", "and", "or", "implies", "=>", "iff", "=",
        "<", "<=", ">", ">=", "+", "-", "*",
    ];
    let mut out: Vec<String> = Vec::new();
    fn walk(t: &Term, known: &[&str], out: &mut Vec<String>) {
        match t.kind() {
            TermInner::Const(c) => {
                let n = c.name.as_str();
                // Numeric literals render as themselves in every target.
                let numeric = !n.is_empty()
                    && n.chars().all(|ch| ch.is_ascii_digit() || ch == '-');
                if !numeric && !known.contains(&n) && !out.iter().any(|x| x == n) {
                    out.push(n.to_owned());
                }
            }
            TermInner::App(f, x) => {
                walk(&f, known, out);
                walk(&x, known, out);
            }
            TermInner::Lam(_, b) => walk(&b, known, out),
            _ => {}
        }
    }
    for step in &cert.steps {
        for h in &step.result.hyps {
            walk(h, KNOWN, &mut out);
        }
        walk(&step.result.concl, KNOWN, &mut out);
    }
    out
}
